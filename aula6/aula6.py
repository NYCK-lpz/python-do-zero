#O que são operadores relaionais?
#Operadores relacionais são utilizados
# para comparar valores, retornando um valor booleano 
# (True    ou False). Eles são muito utilizados em estrut
# uras de decisão, como if e while, para determinar o fluxo 
# do programa com base em condições específicas.


#Operadores relacionais em Python:
# ==  : igual a
# !=  : diferente de
# >   : maior que
# <   : menor que
# >=  : maior ou igual a
# <=  : menor ou igual a

#O RESULTADOS:
True
False

# OPERADORES ==
#Para atribuir um valor 
idade = 18

#Para comparar
idade == 18

# exemplo
idade = 18
print(idade == 18)  # True

# DIFERENTE !=
#Para atribuir um valor
idade = 18

#Para comparar
idade != 18

# exemplo
idade = 18
print(idade != 18)  # False

#MAIOR E MENOR
#Para atribuir um valor
idade = 18

#Para comparar
idade > 18

# exemplo
idade = 18
print(idade > 18)  # False

#MAIOR OU IGUAL >=
#Para atribuir um valor
idade = 18

#Para comparar
idade >= 18

# exemplo
idade = 18
print(idade >= 18)  # True

