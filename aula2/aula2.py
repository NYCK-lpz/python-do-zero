# Exercico 1 
nome = "João"  # String
idade = 25  # Inteiro
float_num = 3.14  # Float
boolean_var = True  # Booleano

print(type(nome))  # <class 'str'>
print(type(idade))  # <class 'int'>
print(type(float_num))  # <class 'float'>
print(type(boolean_var))  # <class 'bool'>

